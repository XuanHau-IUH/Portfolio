export function getLocalizedProjects(lang = 'vi', rawProjectList = rawProjects) {
  const list = projectsI18n[lang] || projectsI18n.vi;
  return list.map((localizedItem, idx) => {
    const raw = rawProjectList.find((p) => p.slug === localizedItem.slug) || rawProjectList[idx] || {};
    const fallbackImage = domainFallbackCovers[localizedItem.slug] !== undefined
      ? domainFallbackCovers[localizedItem.slug]
      : (raw.fallbackImage || null);
    
    // Localize images array labels & slotPurposes
    const images = (raw.images || []).map((img) => {
      const caption = localizedItem.imageCaptions?.[img.id] || img.label || localizedItem.title;
      return {
        ...img,
        label: caption,
        slotPurpose: localizedItem.imageCaptions?.[img.id] || img.slotPurpose || localizedItem.subtitle,
      };
    });

    return {
      ...raw,
      ...localizedItem,
      id: parseInt(localizedItem.index, 10) || idx + 1,
      image: raw.cover || '/projects/ha-long-luxe/01-cover-ha-long-luxe.webp',
      fallbackImage,
      category: projectCategoryMap[localizedItem.slug] || localizedItem.category || 'Vertical SaaS',
      description: localizedItem.subtitle || localizedItem.summary,
      client: localizedItem.domain,
      images: images.length > 0 ? images : [
        {
          id: '01-cover',
          src: raw.cover || fallbackImage,
          label: localizedItem.title,
          slotPurpose: localizedItem.subtitle,
        }
      ],
    };
  });
}
